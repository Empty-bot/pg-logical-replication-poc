-- =============================================================================
-- V1 : la source de vérité. Une table ordinaire possédée par source_app.
--
-- Visibilité par colonne dans ce PoC :
--   id, first_name, last_name, email, region, loyalty_points -> PUBLIÉES
--   internal_notes, credit_card_number                       -> PRIVÉES (ne
--                                                               quittent jamais
--                                                               source_db)
-- Visibilité par ligne : seuls les clients avec region = 'EU' sont publiés.
-- (Les deux règles sont définies en V3.)
-- =============================================================================
CREATE TABLE customers (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name         VARCHAR(100) NOT NULL,
    last_name          VARCHAR(100) NOT NULL,
    email              VARCHAR(255) NOT NULL UNIQUE,
    -- Le NOT NULL compte pour la réplication : cette colonne fera partie de
    -- l'index de REPLICA IDENTITY (V3), et les colonnes d'un tel index doivent
    -- être NOT NULL.
    region             VARCHAR(10)  NOT NULL,
    loyalty_points     INTEGER      NOT NULL DEFAULT 0,
    internal_notes     TEXT,
    credit_card_number VARCHAR(32)
);
